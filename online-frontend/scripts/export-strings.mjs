// Regenerates docs/ONLINE_SITE_STRINGS.md (every Urdu string next to its English one) from src/i18n/ur.ts + en.ts.
// Run from online-frontend/:  npm run strings      (Node 22.18+/24 strips the TypeScript types itself)
import { writeFileSync } from 'node:fs'
import { ur } from '../src/i18n/ur.ts'
import { en } from '../src/i18n/en.ts'

const OUT = '../docs/ONLINE_SITE_STRINGS.md'
const groups = [
  ['brand', 'Brand names'],
  ['nav', 'Header and navigation'],
  ['contact', 'Call / WhatsApp'],
  ['footer', 'Footer'],
  ['social', 'Social links'],
  ['net', 'Offline banner'],
  ['err', 'Generic errors'],
  ['loading', 'Loading'],
  ['soon', 'Placeholders'],
  ['notFound', 'Page not found'],
  ['page', 'Browser tab titles'],
  ['home', 'Home: opening state and "See all"'],
  ['hero', 'Home: hero headline and facts (the two headline lines are placeholders: owner must confirm)'],
  ['cats', 'Home: browse by category'],
  ['new', 'Home: new items'],
  ['offer', 'Home: offer banner'],
  ['deals', 'Home: order by deal'],
  ['why', 'Home: "Why Zoryx" (owner must confirm the claims)'],
  ['popular', 'Home: popular items'],
  ['how', 'Home: how to order'],
  ['gallery', 'Home: gallery'],
  ['reviews', 'Home: customer reviews'],
  ['find', 'Home: find us'],
  ['menu', 'Menu page'],
  ['cart', 'Cart'],
  ['last', 'Last-order banner'],
  ['checkout', 'Checkout'],
  ['v', 'Checkout: field validation'],
  ['e', 'Checkout: server / network errors'],
  ['order', 'Order status page'],
  ['st', 'Order status steps'],
]
const groupOf = (key) => {
  const prefix = key.split('.')[0]
  return groups.find(([p]) => p === prefix)?.[0] ?? 'other'
}
const esc = (s) => String(s).replaceAll('|', '\\|').replaceAll('\n', ' ')

const keys = Object.keys(ur)
const missing = keys.filter((k) => !(k in en)).concat(Object.keys(en).filter((k) => !(k in ur)))
if (missing.length) throw new Error(`ur.ts and en.ts differ: ${missing.join(', ')}`)

let md = `# Online site: Urdu and English strings

Generated by \`npm run strings\` in \`online-frontend/\` from \`src/i18n/ur.ts\` and \`en.ts\`. Do not edit by hand: change the .ts files and regenerate.

## Read this first

- **Every Urdu string below was machine-written (by Claude) and has not been checked by a native speaker** (the three brand names come from the brief, which also asks for a native check). It aims at plain, spoken-style Urdu as the brief asks, but it must be proofread before launch.
- How to review: fix the Urdu in \`src/i18n/ur.ts\` (or send corrections and ask for them to be applied), tick the box, regenerate this file.
- Things to look at especially: the brand names, the hero headline (two lines) and the second "accent" line of every section title (all placeholders), the four "Why Zoryx" claims (they are placeholders and must also be true), payment wording (Easypaisa / JazzCash / bank), and every message that tells a customer what to do next.
- \`{amount}\`, \`{code}\`, \`{price}\`, \`{min}\`, \`{more}\`, \`{area}\`, \`{item}\` are filled in by the site; keep them exactly as written, in the same spelling. Numbers always display in Western digits ("Rs 1,450").
- Strings that come from the shop owner through the staff app (shop name, tagline, address, opening hours, announcement, item and category names, deal names, testimonials, delivery area names) are not in this file: staff type those in Urdu and English themselves.

## Static text outside the translation files

| Where | Urdu | English | Status |
|---|---|---|---|
| \`index.html\` title | زوریکس — ڈیمو ریسٹورنٹ | Zoryx | machine-written, proofread |
| \`index.html\` description | زوریکس، زوریکس — گھر بیٹھے آرڈر کریں۔ | Zoryx, Demo restaurant — order online for delivery. | machine-written, proofread |
| \`index.html\` Open Graph description | گھر بیٹھے آرڈر کریں | Order Zoryx online. | machine-written, proofread |
| \`index.html\` noscript (JavaScript off) | آرڈر کے لیے کال کریں | Please call to order | machine-written, proofread |
| Brand as printed on the logo | زوریکس · ڈیمو ریسٹورنٹ · زوریکس | ZORYX · Demo restaurant · Zoryx | from the brief; **owner must confirm spelling** (the POS docs say "Zoryx") |

`
for (const [prefix, title] of [...groups, ['other', 'Other']]) {
  const rows = keys.filter((k) => groupOf(k) === prefix)
  if (!rows.length) continue
  md += `\n## ${title}\n\n| Key | Urdu | English | Status |\n|---|---|---|---|\n`
  for (const key of rows) {
    const flag = key.startsWith('why.') && !key.endsWith('.accent') ? 'machine-written, proofread **and owner must confirm the claim**' : key.startsWith('hero.line') || key.endsWith('.accent') ? 'machine-written, **placeholder wording: owner must confirm** (second line of a heading, shown in the accent colour)' : key.startsWith('brand.') ? 'taken from the brief (not native-checked), **owner must confirm**' : 'machine-written, proofread'
    md += `| \`${key}\` | ${esc(ur[key])} | ${esc(en[key])} | ☐ ${flag} |\n`
  }
}
md += `\n---\n${keys.length} strings.\n`
writeFileSync(OUT, md)
console.log(`wrote ${OUT} (${keys.length} strings)`)
