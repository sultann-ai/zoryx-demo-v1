// Writes src/brand/theme.css (the Tailwind @theme colour tokens) from src/brand/brand.config.ts.
// Runs before `dev` and `build`, so editing the config is the only step for a colour change.
// Two groups: the raw brand palette (bg-forest, bg-sunflower, ...) and the semantic roles (bg-action, text-ink, ...).
import { writeFile } from 'node:fs/promises'
import { brand } from '../src/brand/brand.config.ts'

const block = (entries) => entries.map(([name, value]) => `  --color-${name}: ${value};`).join('\n')
// `ink` and `white` are both a palette colour and a role/Tailwind default with the same value: emit them once.
const palette = Object.entries(brand.palette).filter(([name]) => !(name in brand.theme) && name !== 'white')
const css = `/* GENERATED by scripts/make-theme.mjs from src/brand/brand.config.ts. Do not edit: change the config. */
@theme {
  /* Brand palette */
${block(palette)}
  /* Roles */
${block(Object.entries(brand.theme))}
}
`
await writeFile(new URL('../src/brand/theme.css', import.meta.url), css)
console.log('theme.css written')
